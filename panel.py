import discord
from discord.ui import Modal, TextInput, View, button
from discord import TextStyle, ButtonStyle, Embed, Interaction
import database
import webhook_logger
import db_sync

def can_manage_reseller(interaction: Interaction) -> bool:
    """
    Checks if the user has access to manage keys in this reseller channel:
    - Main Owner or any added Owner (has access everywhere)
    - The specific Reseller assigned to this channel
    - Server Administrator
    """
    if database.is_owner(interaction.user.id):
        return True
    
    reseller_data = database.get_reseller_by_channel(interaction.channel_id)
    if reseller_data and reseller_data["user_id"] == interaction.user.id:
        return True
    
    if interaction.permissions.administrator:
        return True
        
    return False

