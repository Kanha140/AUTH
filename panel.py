class CreateUserModal(Modal, title="Create User & Key"):
    username = TextInput(
        label="Username",
        placeholder="Enter desired username (e.g. user123)",
        required=True,
        max_length=64
    )
    password = TextInput(
        label="Password",
        placeholder="Enter user password",
        required=True,
        max_length=64
    )
    days = TextInput(
        label="Duration (in Days)",
        placeholder="e.g. 1, 7, 30, 365",
        default="30",
        required=True,
        max_length=5
    )

    async def on_submit(self, interaction: Interaction):
        # 1. Enforcement: Only works in authorized reseller created channels!
        if not database.is_reseller_channel(interaction.channel_id):
            await interaction.response.send_message(
                "❌ **Error:** Keys can ONLY be created inside an authorized reseller-created channel!",
                ephemeral=True
            )
            return

        # 2. Check authorization
        if not can_manage_reseller(interaction):
            await interaction.response.send_message(
                "❌ You do not have permission to generate keys in this channel.",
                ephemeral=True
            )
            return

        try:
            num_days = int(self.days.value.strip())
            if num_days <= 0:
                raise ValueError
        except ValueError:
            await interaction.response.send_message(
                "❌ Days must be a positive whole number (e.g. 30).",
                ephemeral=True
            )
            return

        result = database.create_key(
            username=self.username.value,
            password=self.password.value,
            days=num_days,
            created_by=interaction.user.id,
            channel_id=interaction.channel_id
        )

        if not result["success"]:
            await interaction.response.send_message(f"❌ {result['message']}", ephemeral=True)
            return

        # Public in channel: "SABKOI DEKH PAYEGA ONLY YOU CAN SEE KEY GENRATE MAI NHI RAHEGA"
        embed = Embed(
            title="🔑 Key Generated Successfully",
            description="A new key/user has been registered! Device HWID will **auto-bind** on first login.",
            color=0x2ECC71
        )
        embed.add_field(name="👤 Username", value=f"`{result['username']}`", inline=True)
        embed.add_field(name="🔒 Password", value=f"`{result['password']}`", inline=True)
        embed.add_field(name="⏳ Duration", value=f"`{result['days']} Days`", inline=True)
        embed.add_field(name="📅 Expires At", value=f"`{result['expires_at']}`", inline=False)
        embed.add_field(name="💻 HWID Status", value="`🟢 Ready to auto-bind on first login`", inline=False)
        embed.set_footer(text=f"Generated by {interaction.user.name}", icon_url=interaction.user.display_avatar.url)

        # ephemeral=False so everyone in the reseller channel can see it!
        await interaction.response.send_message(embed=embed, ephemeral=False)

        # Log to Discord Webhook
        await webhook_logger.log_key_generated(
            username=result["username"],
            password=result["password"],
            days=result["days"],
            expires_at=result["expires_at"],
            created_by=interaction.user.id,
            channel_id=interaction.channel_id
        )

        # Trigger Cloud Backup
        db_sync.trigger_cloud_backup()


class DeleteUserModal(Modal, title="Delete User & Key"):
    username = TextInput(
        label="Username",
        placeholder="Enter username to delete",
        required=True,
        max_length=64
    )

    async def on_submit(self, interaction: Interaction):
        uname = self.username.value.strip()
        deleted = database.delete_key(uname)

        if deleted:
            embed = Embed(
                title="🗑️ Key Deleted",
                description=f"User credentials for **`{uname}`** have been permanently removed.",
                color=0xE74C3C
            )
            embed.set_footer(text=f"Deleted by {interaction.user.name}")
            await interaction.response.send_message(embed=embed, ephemeral=False)

            # Webhook log
            await webhook_logger.log_key_deleted(uname, interaction.user.id, interaction.channel_id)
            db_sync.trigger_cloud_backup()
        else:
            await interaction.response.send_message(
                f"❌ User **`{uname}`** was not found in the database.",
                ephemeral=True
            )


class ResetHWIDModal(Modal, title="Reset User HWID"):
    username = TextInput(
        label="Username",
        placeholder="Enter username to reset HWID",
        required=True,
        max_length=64
    )

    async def on_submit(self, interaction: Interaction):
        uname = self.username.value.strip()
        result = database.reset_hwid(uname)

        if not result["success"]:
            await interaction.response.send_message(f"❌ {result['message']}", ephemeral=True)
            return

        embed = Embed(
            title="🔄 HWID Reset Successful",
            description=f"HWID for **`{uname}`** has been cleared.",
            color=0x3498DB
        )
        embed.add_field(name="Status", value="Ready to auto-bind new HWID on next login.", inline=False)
        if result.get("old_hwid"):
            embed.add_field(name="Previous HWID", value=f"`{result['old_hwid']}`", inline=False)
        else:
            embed.add_field(name="Previous HWID", value="*None (Was never bound)*", inline=False)
        embed.set_footer(text=f"Reset by {interaction.user.name}")

        await interaction.response.send_message(embed=embed, ephemeral=False)

        # Webhook log
        await webhook_logger.log_hwid_reset(uname, interaction.user.id, result.get("old_hwid"))
        db_sync.trigger_cloud_backup()


class KeyInfoModal(Modal, title="Check Key & HWID Info"):
    username = TextInput(
        label="Username",
        placeholder="Enter username to inspect",
        required=True,
        max_length=64
    )

    async def on_submit(self, interaction: Interaction):
        uname = self.username.value.strip()
        info = database.get_key_info(uname)

        if not info:
            await interaction.response.send_message(
                f"❌ User **`{uname}`** not found in the database.",
                ephemeral=True
            )
            return

        status_text = "🔴 Expired" if info["is_expired"] else "🟢 Active"
        hwid_text = f"`{info['hwid']}`" if info.get("hwid") else "🟡 *Not Bound (Will auto-bind on 1st login)*"
        last_login_text = f"`{info['last_login']} UTC`" if info.get("last_login") else "*Never logged in*"

        embed = Embed(
            title=f"📋 Key Info: {info['username']}",
            color=0x9B59B6
        )
        embed.add_field(name="👤 Username", value=f"`{info['username']}`", inline=True)
        embed.add_field(name="🔒 Password", value=f"`{info['password']}`", inline=True)
        embed.add_field(name="📊 Status", value=status_text, inline=True)
        embed.add_field(name="📅 Expires At", value=f"`{info['expires_at']} UTC`", inline=True)
        embed.add_field(name="⏳ Time Remaining", value=f"{info['remaining_days']}d {info['remaining_hours']}h", inline=True)
        embed.add_field(name="🕒 Last Login", value=last_login_text, inline=True)
        embed.add_field(name="💻 Bound HWID", value=hwid_text, inline=False)
        embed.add_field(name="🛠️ Created By", value=f"<@{info['created_by']}>", inline=False)

        await interaction.response.send_message(embed=embed, ephemeral=True)


